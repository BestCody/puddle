import { test, expect } from '@playwright/test'

test.beforeEach(async ({ context }) => {
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
})

test('sidebar actions do not intercept navigation in short desktop windows', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'One mouse-driven short desktop regression')
  await page.setViewportSize({ width: 844, height: 393 })
  await page.goto('/matches')
  const sidebar = page.getByRole('complementary', { name: 'Puddle sidebar' })
  await expect(sidebar).toHaveClass(/is-concise/)
  const nav = await sidebar.getByRole('navigation').boundingBox()
  const settings = await sidebar.getByRole('button', { name: 'Settings', exact: true }).boundingBox()
  const signout = await sidebar.getByRole('button', { name: 'Sign out' }).boundingBox()
  expect(nav.y + nav.height).toBeLessThanOrEqual(settings.y)
  expect(settings.y + settings.height).toBeLessThanOrEqual(signout.y)
  await sidebar.getByRole('link', { name: 'Profile', exact: true }).scrollIntoViewIfNeeded()
  await sidebar.getByRole('link', { name: 'Profile', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Alex Puddle', exact: true })).toBeVisible()
})

test('touch landscape keeps Messages mobile, including after rotation', async ({ browser, baseURL }, testInfo) => {
  test.skip(testInfo.project.name !== 'phone-landscape', 'One real touch-viewport regression')
  const context = await browser.newContext({ baseURL, viewport: { width: 844, height: 393 }, hasTouch: true, isMobile: true })
  await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  const page = await context.newPage()
  try {
    await page.goto('/matches')
    const nav = page.getByRole('navigation', { name: 'Puddle mobile navigation' })
    await expect(nav).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Friends sections' })).toBeVisible()
    await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toBeHidden()
    await page.getByRole('button', { name: /Jamie See you/ }).click()
    const input = page.getByRole('textbox', { name: 'Message', exact: true })
    await expect(input).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Friends sections' })).toBeHidden()
    const composer = await input.boundingBox(), navbar = await nav.boundingBox()
    expect(composer.y + composer.height).toBeLessThanOrEqual(navbar.y)
    await page.setViewportSize({ width: 393, height: 844 })
    await expect(input).toBeVisible()
    await expect(nav).toBeVisible()
    await page.getByRole('link', { name: 'Back to conversations' }).click()
    await expect(page.getByRole('navigation', { name: 'Friends sections' })).toBeVisible()
    await page.setViewportSize({ width: 844, height: 393 })
    await nav.getByRole('link', { name: 'Profile', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Settings', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Settings', exact: true }).click()
    await page.getByRole('link', { name: 'Appearance ›', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Appearance', exact: true })).toBeVisible()
    await page.goto('/plans')
    const savedSearch = page.getByRole('searchbox', { name: 'Search saved puddles' })
    const searchBar = await savedSearch.boundingBox(), savedNav = await nav.boundingBox()
    expect(searchBar.y + searchBar.height).toBeLessThanOrEqual(savedNav.y)
    await page.goto('/map')
    await expect(page.getByRole('button', { name: 'Create a puddle...', exact: true })).toBeVisible()
    const create = await page.getByRole('button', { name: 'Create a puddle...', exact: true }).boundingBox()
    const feedNav = await nav.boundingBox()
    expect(create.y + create.height).toBeLessThanOrEqual(feedNav.y)
  } finally { await context.close() }
})

test('modified Saved clicks preserve native new-tab navigation', async ({ page, context }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'Desktop modifier-click regression')
  await page.goto('/plans')
  const popup = context.waitForEvent('page')
  await page.getByRole('link', { name: 'Open Maple Grove Park', exact: true }).first().click({ modifiers: ['Control'] })
  const opened = await popup
  await expect(opened).toHaveURL(/\/plans\/visual-place-0$/)
  await expect(page.getByRole('dialog', { name: 'Maple Grove Park details' })).toHaveCount(0)
  await opened.close()
})

test('Map popup actions have separate usable hit areas', async ({ page }) => {
  await page.goto('/map?view=map')
  const open = page.getByRole('link', { name: 'Open place', exact: true })
  const directions = page.getByRole('link', { name: 'Directions', exact: true })
  await expect(open).toBeVisible()
  const a = await open.boundingBox(), b = await directions.boundingBox()
  expect(a.height).toBeGreaterThanOrEqual(44)
  expect(b.height).toBeGreaterThanOrEqual(44)
  expect(a.x + a.width <= b.x || a.y + a.height <= b.y).toBe(true)
})

test('all remaining mobile text inputs render at readable focus-safe sizes', async ({ page }, testInfo) => {
  test.skip(!['phone', 'small-phone'].includes(testInfo.project.name), 'Portrait input regressions')
  async function readable(locator) {
    await expect(locator.first()).toBeVisible()
    const sizes = await locator.evaluateAll(nodes => nodes.map(node => parseFloat(getComputedStyle(node).fontSize)))
    expect(sizes.every(size => size >= 16), JSON.stringify(sizes)).toBe(true)
  }
  await page.goto('/landing.html')
  await page.getByRole('link', { name: 'Login', exact: true }).click()
  await page.getByRole('tab', { name: 'Sign up', exact: true }).click()
  await readable(page.locator('.mobile-login-dialog .landing-signup-form input:not([type=hidden]):not([type=checkbox])'))
  await page.goto('/discover')
  await page.getByRole('button', { name: 'Open filters' }).click()
  await readable(page.getByRole('textbox', { name: 'Location Search' }))
  await page.goto('/plans')
  await readable(page.getByRole('searchbox', { name: 'Search saved puddles' }))
  await page.goto('/plans/visual-place-0')
  await page.locator('details').filter({ has: page.getByText('Plan a visit', { exact: true }) }).locator('summary').click()
  await readable(page.locator('details[open] input:not([type=hidden])'))
  await page.goto('/map')
  await page.locator('summary[aria-label="Comment on An afternoon outdoors"]').first().click()
  await readable(page.locator('details[open] input[name=comment_body]'))
  await page.goto('/appeals')
  await readable(page.getByRole('textbox'))
  await page.goto('/onboarding')
  await readable(page.getByRole('textbox', { name: 'Display name', exact: true }))
  await readable(page.getByRole('textbox', { name: /^Username/ }))
  await readable(page.getByRole('textbox', { name: /^Birth date/ }))
})
